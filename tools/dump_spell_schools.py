"""Regenerate bartlebot/data/spell_schools.json from the game's Root.wad.

A saved deck holds template names and counts, so the only way to group a deck's
cards by school -- which is how the game's own deck window lists them -- is to carry
each template's school alongside. That is ``m_sMagicSchoolName`` on the spell
template, a plain string ("Ice", "Storm"), not a langcode.

WHERE THE DATA COMES FROM
    The same place ``dump_spell_names.py`` reads: each spell under ``Spells/`` in
    Root.wad is a BINd blob, and the WAD path's stem is the template's internal
    name, so only the *field* needs deserializing. See that tool's header for why
    the named field is read rather than scanned for.

THE 41 NAMES THAT APPEAR TWICE
    Template names are not unique in the WAD: 41 of them exist both under
    ``Spells/CastleMagic/`` and as a real spell, e.g. ``Banshee`` is both
    ``CastleMagic`` and ``Death``. In every one of the 41 the two files name the
    *same* art, so they are the same card filed twice, and the difference is only
    which school the copy claims.

    A deck stores the bare name, so nothing downstream can tell the copies apart --
    this tool has to pick one. It keeps the real school, because a card in a combat
    deck is never the castle-magic copy. ``CastleMagic``, ``Cantrips``,
    ``Gardening``, ``Fishing`` and ``WhirlyBurly`` are all kept out of the order this
    way; see ``bartlebot/spell_schools.py``.

USAGE
    uv run python tools/dump_spell_schools.py
    uv run python tools/dump_spell_schools.py --wad "D:/Games/Wizard101/Data/GameData/Root.wad"
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import date
from pathlib import Path, PurePosixPath

from katsuba.op import STATEFUL_FLAGS, Serializer, SerializerOptions, TypeList
from katsuba.wad import Archive

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from bartlebot.spell_schools import SCHOOL_ORDER, SCHOOLS_PATH  # noqa: E402

DEFAULT_WAD = Path(r"C:\ProgramData\KingsIsle Entertainment\Wizard101\Data\GameData\Root.wad")
DEFAULT_TYPES = Path(__file__).resolve().parent / "r800294_WizardDev.json"
SPELLS_GLOB = "Spells/**/*.xml"


def _decode(value) -> str | None:
    if value is None:
        return None
    if isinstance(value, bytes):
        return value.decode("utf-8", errors="replace")
    return str(value)


def _build_serializer(types_path: Path) -> Serializer:
    types = TypeList.open(str(types_path))
    opts = SerializerOptions()
    opts.flags = STATEFUL_FLAGS
    opts.shallow = False
    opts.skip_unknown_types = True
    return Serializer(opts, types)


def build_snapshot(wad_path: Path, types_path: Path) -> dict:
    archive = Archive.mmap(str(wad_path))
    ser = _build_serializer(types_path)

    schools: dict[str, str] = {}
    skipped = 0
    errors = 0
    replaced = 0
    for path in archive.iter_glob(SPELLS_GLOB):
        name = PurePosixPath(path).stem
        try:
            data = archive[path]
            if data.startswith(b"BINd"):
                data = data[4:]
            school = _decode(ser.deserialize(data).get("m_sMagicSchoolName"))
        except Exception:
            errors += 1
            continue
        if not school:
            skipped += 1
            continue
        held = schools.get(name)
        if held is not None:
            # The duplicate-name case in the header: keep whichever copy claims a real
            # school, whatever order the archive happened to hand them over in.
            if held in SCHOOL_ORDER or school not in SCHOOL_ORDER:
                continue
            replaced += 1
        schools[name] = school

    return {
        "_comment": "Generated by tools/dump_spell_schools.py -- do not hand-edit. See that file for how.",
        "generated": date.today().isoformat(),
        "source": str(wad_path),
        "skipped": skipped,
        "errors": errors,
        "duplicates_resolved": replaced,
        "schools": schools,
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--wad", type=Path, default=DEFAULT_WAD, help="path to Root.wad")
    ap.add_argument("--types", type=Path, default=DEFAULT_TYPES, help="path to a wiztype types JSON dump")
    ap.add_argument("--out", type=Path, default=SCHOOLS_PATH, help="where to write the snapshot")
    args = ap.parse_args()

    if not args.wad.exists():
        print(f"Root.wad not found at {args.wad}; pass --wad")
        return 1
    if not args.types.exists():
        print(f"types JSON not found at {args.types}; pass --types")
        return 1

    snapshot = build_snapshot(args.wad, args.types)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(snapshot, indent=1, ensure_ascii=False), encoding="utf-8")

    counts: dict[str, int] = {}
    for school in snapshot["schools"].values():
        counts[school] = counts.get(school, 0) + 1
    print(f"wrote {args.out} ({args.out.stat().st_size // 1024} KB)")
    print(f"  {len(snapshot['schools'])} templates, {snapshot['skipped']} with no school, {snapshot['errors']} errors")
    print(f"  {snapshot['duplicates_resolved']} duplicate names resolved to their real school")
    for school in SCHOOL_ORDER:
        print(f"    {school:9} {counts.get(school, 0)}")
    for school, count in sorted(counts.items()):
        if school not in SCHOOL_ORDER:
            print(f"    {school:9} {count}  (not a deck school -- sorts last)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
