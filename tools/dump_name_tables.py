"""Regenerate bartlebot/data/name_tables.json from the game's Root.wad.

Run this only when Wizard101 adds new character names, which is rare -- the tables show
4 to 10 append batches across the game's lifetime.  Everything else reads the checked-in
snapshot, so neither the app nor its tests need the game installed.

WHY A SNAPSHOT IS SAFE
    The obvious worry with caching an index table is that an insertion shifts every later
    index and silently decodes wrong names.  That cannot happen here: KI *appends*.  Each
    table is an alphabetically sorted original block followed by later batches, each sorted
    within itself --

        FirstName_HumanMale   10 runs: [145, 1, 1, 4, 1, 1, 1, 40, 53, 3]
        MiddleName_Human       4 runs: [84, 1, 129, 35]
        LastName_Human         6 runs: [78, 34, 18, 37, 81, 1]

    -- which is what appending to a sorted seed list looks like.  It also has to be that
    way: the server stores each character's name as indices, so inserting a name mid-table
    would rename every existing wizard.

    So a stale snapshot cannot corrupt an existing name.  It can only fail to know a newly
    added one, and that shows up as an index past the end of the table -- detectable, and
    reported as such by bartlebot.name_tables rather than guessed at.

USAGE
    poetry run python tools/dump_name_tables.py
    poetry run python tools/dump_name_tables.py --wad "D:/Games/Wizard101/Data/GameData/Root.wad"
"""

from __future__ import annotations

import argparse
import asyncio
import json
import re
import sys
from datetime import date
from pathlib import Path

from wizwalker.file_readers.wad import Wad

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from bartlebot.name_tables import TABLE_NAMES, TABLES_PATH  # noqa: E402

DEFAULT_WAD = Path(r"C:\ProgramData\KingsIsle Entertainment\Wizard101\Data\GameData\Root.wad")
NAMES_XML = "CharacterNames.xml"
LANG_TEMPLATE = "Locale/{locale}/CharacterNames.lang"


def parse_lang(raw: bytes) -> dict[str, str]:
    """Parse a .lang file into {key: display text}.

    Records are three lines -- key, blank, value -- in UTF-16LE with CRLF endings.
    """
    lines = raw.decode("utf-16-le").split("\r\n")
    return {
        line: lines[i + 2]
        for i, line in enumerate(lines)
        if line.startswith(("First_", "Middle_", "Last_")) and i + 2 < len(lines)
    }


def parse_xml_tables(xml: str) -> dict[tuple[str, str], list[str]]:
    """Ordered key lists, keyed by (table name, locale).

    Order is what matters: m_nameKeys indexes position in this list, not the numeric
    suffix of the key. First_Boy_102 is "Luke" but sits at index 100.
    """
    return {
        (name, locale): re.findall(r"<CharacterName>([^<]+)</CharacterName>", body)
        for name, locale, body in re.findall(r'<Table Name="([^"]+)" Locale="([^"]+)">(.*?)</Table>', xml, re.S)
    }


async def build_snapshot(wad_path: Path) -> dict:
    wad = Wad(str(wad_path))
    xml = (await wad.get_file(NAMES_XML)).decode("utf-8-sig", "replace")
    by_table = parse_xml_tables(xml)
    locales = sorted({locale for _name, locale in by_table})

    tables: dict[str, dict[str, list[str]]] = {}
    for locale in locales:
        lang = parse_lang(await wad.get_file(LANG_TEMPLATE.format(locale=locale)))
        resolved = {table: [lang.get(key, key) for key in by_table.get((table, locale), [])] for table in TABLE_NAMES}
        # A locale with no usable tables would only add noise to the snapshot.
        if any(resolved.values()):
            tables[locale] = resolved

    return {
        "_comment": "Generated by tools/dump_name_tables.py -- do not hand-edit. See that file for why a snapshot is safe.",
        "generated": date.today().isoformat(),
        "source": str(wad_path),
        "locales": tables,
    }


async def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--wad", type=Path, default=DEFAULT_WAD, help="path to Root.wad")
    ap.add_argument("--out", type=Path, default=TABLES_PATH, help="where to write the snapshot")
    args = ap.parse_args()

    if not args.wad.exists():
        print(f"Root.wad not found at {args.wad}; pass --wad")
        return 1

    snapshot = await build_snapshot(args.wad)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(snapshot, indent=1, ensure_ascii=False), encoding="utf-8")

    print(f"wrote {args.out} ({args.out.stat().st_size // 1024} KB)")
    for locale, tables in snapshot["locales"].items():
        counts = ", ".join(f"{name}={len(values)}" for name, values in tables.items())
        print(f"  {locale:<6} {counts}")
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
