"""Regenerate bartlebot/data/world_names.json from the game's Root.wad.

Run this when a game patch adds a world, or renames one in any locale. Everything else
reads the checked-in snapshot, so neither the app nor its tests need the game installed.

WHAT IT READS
    Locale/<loc>/WorldNames.lang, which is keyed by the world's zone-name prefix and
    valued with the localized text the spiral door lists:

        WizardCity   -> Wizard City / Sorcelleville / Magouboli ...
        DragonSpire  -> Dragonspyre / Drachenfels / Roc du dragon ...

    Every key is captured, not just the spiral door ones. The extras cost nothing, and
    keeping them means the snapshot can answer "is this a known world key" for zones
    like G14_DM that are not on the door -- see bartlebot/worlds.py on why the door
    list itself has to be curated by hand.

WHY A SNAPSHOT IS SAFE
    Nothing here is index-based: a world is looked up by its own key, so a stale
    snapshot cannot mis-name a world. It can only fail to list one the game has just
    added, which surfaces as a load-time warning naming the missing key.

USAGE
    poetry run python tools/dump_world_names.py
    poetry run python tools/dump_world_names.py --wad "D:/Games/Wizard101/Data/GameData/Root.wad"
    poetry run python tools/dump_world_names.py --verify      # no write; check the current file
"""

from __future__ import annotations

import argparse
import asyncio
import json
import sys
from datetime import date
from pathlib import Path

from wizwalker.file_readers.wad import Wad

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from bartlebot.worlds import LOCALES, SPIRAL_DOOR_WORLDS, WORLD_NAMES_PATH  # noqa: E402

# World names include Greek, which a cp1252 console cannot encode. Without this the
# tool dies on its own progress output.
sys.stdout.reconfigure(encoding="utf-8", errors="replace")

DEFAULT_WAD = Path(r"C:\ProgramData\KingsIsle Entertainment\Wizard101\Data\GameData\Root.wad")

LANG_FILE = "WorldNames"


def parse_lang(raw: bytes) -> dict[str, str]:
    """Parse a .lang file into {key: display text}.

    UTF-16LE with CRLF endings, a one-line header, then fixed three-line records:

        key
        translator description, OFTEN BUT NOT ALWAYS BLANK
        display text

    The middle line is the trap -- it reads as blank in most records, so a parser that
    requires it blank silently drops every documented key. WorldNames has one such
    record ("Crafting"), so this is not hypothetical here either. Slice at a fixed
    stride rather than walking; see tools/dump_dialog_captions.py, same format.
    """
    lines = raw.decode("utf-16-le", errors="replace").lstrip("\ufeff").split("\r\n")
    return {lines[i]: lines[i + 2] for i in range(1, len(lines) - 2, 3) if lines[i]}


async def build_snapshot(wad_path: Path) -> dict:
    wad = Wad(str(wad_path))
    available = set(await wad.names())

    tables: dict[str, dict[str, str]] = {}
    for locale in LOCALES:
        path = f"Locale/{locale}/{LANG_FILE}.lang"
        if path not in available:
            print(f"  !! {path}: not in the archive")
            continue
        tables[locale] = parse_lang(await wad.get_file(path))

    keys = sorted({key for table in tables.values() for key in table})
    worlds = {
        key: by_locale
        for key in keys
        if (by_locale := {locale: text for locale in LOCALES if (text := tables.get(locale, {}).get(key))})
    }

    return {
        "_comment": (
            "Generated by tools/dump_world_names.py -- do not hand-edit. "
            "See bartlebot/worlds.py for how these are used."
        ),
        "generated": date.today().isoformat(),
        "source": str(wad_path),
        "worlds": worlds,
    }


def verify(snapshot: dict) -> int:
    """Report spiral door worlds the snapshot cannot name. Returns an exit code."""
    worlds: dict[str, dict[str, str]] = snapshot.get("worlds", {})
    problems = 0

    for key in SPIRAL_DOOR_WORLDS:
        by_locale = worlds.get(key)
        if not by_locale:
            print(f"  !! {key}: absent from the snapshot")
            problems += 1
        elif "en-US" not in by_locale:
            # en-US is the fallback every other locale leans on when untranslated, and
            # worlds.label() shows it in the editor. A key without it is unusable.
            print(f"  !! {key}: no en-US name")
            problems += 1

    # Not a failure -- an untranslated world is normal, and those clients show the
    # English name -- but worth seeing, since it is what a locale-specific "entry not
    # found on any page" would trace back to.
    for key in SPIRAL_DOOR_WORLDS:
        absent = [locale for locale in LOCALES if locale not in worlds.get(key, {})]
        if absent:
            print(f"  ~  {key}: untranslated in {', '.join(absent)} (will match on en-US)")

    return 1 if problems else 0


async def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--wad", type=Path, default=DEFAULT_WAD, help="path to Root.wad")
    ap.add_argument("--out", type=Path, default=WORLD_NAMES_PATH, help="where to write the snapshot")
    ap.add_argument("--verify", action="store_true", help="check the existing snapshot; do not write")
    args = ap.parse_args()

    if args.verify:
        if not args.out.exists():
            print(f"no snapshot at {args.out}")
            return 1
        snapshot = json.loads(args.out.read_text(encoding="utf-8"))
        print(f"verifying {args.out} ({len(snapshot.get('worlds', {}))} keys)")
        code = verify(snapshot)
        print("ok" if code == 0 else "problems found")
        return code

    if not args.wad.exists():
        print(f"Root.wad not found at {args.wad}; pass --wad")
        return 1

    snapshot = await build_snapshot(args.wad)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(snapshot, indent=1, ensure_ascii=False), encoding="utf-8")

    worlds = snapshot["worlds"]
    print(f"wrote {args.out} ({len(worlds)} keys, {len(SPIRAL_DOOR_WORLDS)} of them on the spiral door)")
    for key in SPIRAL_DOOR_WORLDS:
        by_locale = worlds.get(key, {})
        print(f"  {key:<14} {len(by_locale)} locale(s): {by_locale.get('en-US', '??')}")
    print()
    return verify(snapshot)


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
