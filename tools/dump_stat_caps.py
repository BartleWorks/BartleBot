"""Regenerate bartlebot/game/data/stat_caps.json from the game's Root.wad.

Challenge Mode level scales a player to its dungeon's level by the **stat caps**: each
stat is scaled by the cap at the dungeon's level over the cap at the player's own. Only
max health and max mana matter to BartleBot, because a player leaves a Challenge Mode
dungeon with the health and mana it had inside, under caps that are no longer scaled.
``bartlebot/game/stat_caps.py`` has the rest.

WHERE THE DATA COMES FROM
    ``LevelScaledData.xml`` at the root of Root.wad: one ``LevelScaledInfo`` per school
    per ten levels, 10 to 180, each with ``m_canonicalMaxHealth`` and
    ``m_canonicalMaxMana`` among a hundred other caps. Its ``m_statsFloorPercent`` is the
    same shape and is zero for both health and mana, so it puts no floor under either and is
    not carried.

USAGE
    uv run python tools/dump_stat_caps.py
    uv run python tools/dump_stat_caps.py --wad "D:/Games/Wizard101/Data/GameData/Root.wad"
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import date
from pathlib import Path

from katsuba.op import STATEFUL_FLAGS, Serializer, SerializerOptions, TypeList
from katsuba.wad import Archive

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from bartlebot.game.art_extraction import TYPE_DUMP_DIR, newest_type_dump  # noqa: E402
from bartlebot.game.stat_caps import CAPS_PATH  # noqa: E402

DEFAULT_WAD = Path(r"C:\ProgramData\KingsIsle Entertainment\Wizard101\Data\GameData\Root.wad")
# The newest dump, from game/data/ where the app ships it or tools/ where older ones stay.
DEFAULT_TYPES = newest_type_dump(TYPE_DUMP_DIR, Path(__file__).resolve().parent)
DATA_FILE = "LevelScaledData.xml"


def _build_serializer(types_path: Path) -> Serializer:
    types = TypeList.open(str(types_path))
    opts = SerializerOptions()
    opts.flags = STATEFUL_FLAGS
    opts.shallow = False
    opts.skip_unknown_types = True
    return Serializer(opts, types)


def build_snapshot(wad_path: Path, types_path: Path) -> dict:
    archive = Archive.mmap(str(wad_path))
    data = bytes(archive[DATA_FILE])
    if data.startswith(b"BINd"):
        data = data[4:]
    root = _build_serializer(types_path).deserialize(data)

    caps: dict[str, dict[str, dict[str, int]]] = {}
    for entry in root.get("m_levelScaledInfoList"):
        school = entry.get("m_school").decode("utf-8")
        caps.setdefault(school, {})[str(entry.get("m_level"))] = {
            "health": round(entry.get("m_canonicalMaxHealth")),
            "mana": round(entry.get("m_canonicalMaxMana")),
        }
    for school, levels in caps.items():
        caps[school] = dict(sorted(levels.items(), key=lambda item: int(item[0])))

    return {
        "_comment": "Generated by tools/dump_stat_caps.py -- do not hand-edit. See that file for how.",
        "generated": date.today().isoformat(),
        "source": str(wad_path),
        "caps": dict(sorted(caps.items())),
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--wad", type=Path, default=DEFAULT_WAD, help="path to Root.wad")
    ap.add_argument("--types", type=Path, default=DEFAULT_TYPES, help="path to a wiztype types JSON dump")
    ap.add_argument("--out", type=Path, default=CAPS_PATH, help="where to write the snapshot")
    args = ap.parse_args()

    if not args.wad.exists():
        print(f"Root.wad not found at {args.wad}; pass --wad")
        return 1
    if not args.types.exists():
        print(f"Types dump not found at {args.types}; pass --types")
        return 1

    snapshot = build_snapshot(args.wad, args.types)
    args.out.write_text(json.dumps(snapshot, indent=2) + "\n", encoding="utf-8")
    counts = {school: len(levels) for school, levels in snapshot["caps"].items()}
    print(f"Wrote {args.out}: {counts}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
