"""Regenerate bartlebot/data/reagent_nodes.json from the game files.

Run this when a game patch adds a harvestable reagent node, or renames one. The snapshot
is what test_every_reagent_id_names_a_real_entity checks shipped collect_reagent nodes
against, so neither it nor the app needs the game installed.

WHAT IT READS
    Every world-entity template under Root.wad's ObjectData/ (the same family
    dump_entity_names.py reads: GameObjectTemplate minus the ItemTemplate branch), keeping
    those whose m_adjectiveList carries "Reagent". Each one's m_objectName is the ID a
    collect_reagent node names -- what the Entity Browser's ID column shows.

WHY NOT entity_names.json
    That snapshot joins an object name to its display name, and a reagent node has none:
    m_displayName is empty on every one. So they are all dropped there, and a typo'd
    reagent ID is indistinguishable from a real one without this list.

WHY THE ADJECTIVE, NOT THE FOLDER
    Most nodes sit in ObjectData/Reagent_Nodes/, but the Mooshu raid's essences and plants
    do not, and a look-alike can sit in the folder's neighborhood without being harvestable:
    Wysteria's "Black Lotus_PAGauntlet" uses the same model and no Reagent adjective. Nor is
    the file stem the ID: Reagent_Nodes/Antiquitie.xml is "Antiquity".

ONE ID IS SPELLED WRONG IN THE GAME
    "Scraplron" -- a lowercase L for the I of Scrap Iron. It is the real ID, and a bot must
    use it as written. Do not "fix" it in the snapshot or in a bot.

USAGE
    uv run python tools/dump_reagent_nodes.py              # a few seconds
    uv run python tools/dump_reagent_nodes.py --verify     # no write; check the current file
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import date
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))
sys.path.insert(0, str(REPO / "tools" / "zone_graph"))

from dump_entity_names import entity_template_hashes  # noqa: E402
from wad_common import DEFAULT_TYPES, GAME_DATA, Deserializer, root_wad, text  # noqa: E402

from bartlebot.entity_names import REAGENT_NODES_PATH  # noqa: E402

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

_REAGENT_ADJECTIVE = "Reagent"


def build_snapshot(game_data: Path, types_path: Path = DEFAULT_TYPES) -> dict:
    root = root_wad(game_data)
    wanted = entity_template_hashes(types_path)
    deserialize = Deserializer(types_path)

    ids: set[str] = set()
    for path in sorted(root.iter_glob("ObjectData/**/*.xml")):
        try:
            template = deserialize(bytes(root[path]))
        except Exception:
            continue  # a template our type dump cannot read; it predates or postdates the dump
        if template.type_hash not in wanted:
            continue
        adjectives = {text(a) for a in (template.get("m_adjectiveList") or [])}
        if _REAGENT_ADJECTIVE in adjectives and (name := text(template.get("m_objectName"))):
            ids.add(name)

    return {
        "_comment": "Generated by tools/dump_reagent_nodes.py -- do not hand-edit. See bartlebot/entity_names.py.",
        "generated": date.today().isoformat(),
        "ids": sorted(ids),
    }


def verify(snapshot: dict) -> int:
    """Report what the snapshot holds. Returns an exit code: 1 only when it holds nothing."""
    ids = snapshot.get("ids", [])
    print(f"  {len(ids)} reagent node IDs")
    return 0 if ids else 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--game-data", type=Path, default=GAME_DATA, help="the Wizard101 Data/GameData directory")
    ap.add_argument("--types", type=Path, default=DEFAULT_TYPES, help="the wiztype dump to read classes from")
    ap.add_argument("--out", type=Path, default=REAGENT_NODES_PATH, help="where to write the snapshot")
    ap.add_argument("--verify", action="store_true", help="check the existing snapshot; do not write")
    args = ap.parse_args()

    if args.verify:
        snapshot = json.loads(args.out.read_text(encoding="utf-8"))
    else:
        snapshot = build_snapshot(args.game_data, args.types)
        args.out.write_text(json.dumps(snapshot, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"wrote {args.out}: {len(snapshot['ids'])} reagent node IDs")
    code = verify(snapshot)
    print("ok" if code == 0 else "problems found")
    return code


if __name__ == "__main__":
    sys.exit(main())
