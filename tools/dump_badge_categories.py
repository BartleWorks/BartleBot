"""Regenerate bartlebot/data/badge_categories.json from the game's Root.wad.

Run this when a game patch adds a badge category, reorders them, or renames one in any
locale. Everything else reads the checked-in snapshot, so neither the app nor its tests
need the game installed.

WHAT IT READS
    ``BadgeFilterDescriptions.xml``, a BINd list the badge page is built from. Each entry
    carries a stable filter name, the icon the page draws for it, and a key into
    ``Locale/<loc>/BadgeFilterNames.lang``:

        m_filterName  4Dungeons
        m_filterIcon  GUI/BadgeCategory/Badge_Category_Dungeons.dds
        m_displayKey  BadgeFilterNames_00000033   -> "Four Dungeons Badges"

    The list order is kept: it is the order the bot library's folders follow.

WHY THE ICON PATH IS SNAPSHOTTED
    Several icons are not named for their category -- Five B.O.X.E.S. draws
    ``Badge_Category_Maestro_Events``, Special Event draws ``Badge_Category_Deckathalon``
    -- so the path cannot be derived from the key. It is a name, not an asset, and is
    tracked on the same terms as ``spell_names.json``; the texture itself is extracted
    per machine by ``tools/extract_card_art.py``.

USAGE
    uv run python tools/dump_badge_categories.py
    uv run python tools/dump_badge_categories.py --wad "D:/Games/Wizard101/Data/GameData/Root.wad"
    uv run python tools/dump_badge_categories.py --verify      # no write; check the current file
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import date
from pathlib import Path

from katsuba.op import LazyList, LazyObject
from katsuba.wad import Archive

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from bartlebot.badge_categories import BADGE_CATEGORIES_PATH  # noqa: E402
from bartlebot.worlds import LOCALES  # noqa: E402
from tools.dump_world_names import parse_lang  # noqa: E402
from tools.extract_card_art import DEFAULT_TYPES, _build_serializer, _decode  # noqa: E402

# Category names include Greek, which a cp1252 console cannot encode.
sys.stdout.reconfigure(encoding="utf-8", errors="replace")

DEFAULT_WAD = Path(r"C:\ProgramData\KingsIsle Entertainment\Wizard101\Data\GameData\Root.wad")

DESCRIPTIONS_FILE = "BadgeFilterDescriptions.xml"
LANG_FILE = "BadgeFilterNames"


def _read_descriptions(archive: Archive, types_path: Path) -> list[dict]:
    data = bytes(archive[DESCRIPTIONS_FILE])
    if data.startswith(b"BINd"):
        data = data[4:]
    root = _build_serializer(types_path).deserialize(data)
    entries = root.get("m_badgeFilterDescriptionList")
    if not isinstance(entries, LazyList):
        raise ValueError(f"{DESCRIPTIONS_FILE} has no m_badgeFilterDescriptionList")
    return [entry for entry in entries if isinstance(entry, LazyObject)]


def build_snapshot(wad_path: Path, types_path: Path) -> dict:
    archive = Archive.mmap(str(wad_path))
    tables: dict[str, dict[str, str]] = {}
    for locale in LOCALES:
        path = f"Locale/{locale}/{LANG_FILE}.lang"
        if path not in set(archive.iter_glob(path)):
            print(f"  !! {path}: not in the archive")
            continue
        tables[locale] = parse_lang(bytes(archive[path]))

    categories = []
    for entry in _read_descriptions(archive, types_path):
        key = _decode(entry.get("m_filterName"))
        icon = _decode(entry.get("m_filterIcon"))
        display_key = _decode(entry.get("m_displayKey")) or ""
        if not key:
            continue
        # "BadgeFilterNames_00000033" -> the "00000033" record of BadgeFilterNames.lang.
        record = display_key.rpartition("_")[2]
        names = {locale: text for locale in LOCALES if (text := tables.get(locale, {}).get(record))}
        categories.append({"key": key, "icon": icon, "names": names})

    return {
        "_comment": (
            "Generated by tools/dump_badge_categories.py -- do not hand-edit. "
            "See bartlebot/badge_categories.py for how these are used."
        ),
        "generated": date.today().isoformat(),
        "source": str(wad_path),
        "categories": categories,
    }


def verify(snapshot: dict) -> int:
    """Report categories the snapshot cannot name or draw. Returns an exit code."""
    problems = 0
    seen: set[str] = set()
    for category in snapshot.get("categories", []):
        key = category.get("key")
        if key in seen:
            print(f"  !! {key}: listed twice")
            problems += 1
        seen.add(key)
        if not category.get("icon"):
            print(f"  !! {key}: no icon")
            problems += 1
        if "en-US" not in category.get("names", {}):
            print(f"  !! {key}: no en-US name")
            problems += 1
    return 1 if problems else 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--wad", type=Path, default=DEFAULT_WAD, help="path to Root.wad")
    ap.add_argument("--types", type=Path, default=DEFAULT_TYPES, help="path to a wiztype types JSON dump")
    ap.add_argument("--out", type=Path, default=BADGE_CATEGORIES_PATH, help="where to write the snapshot")
    ap.add_argument("--verify", action="store_true", help="check the existing snapshot; do not write")
    args = ap.parse_args()

    if args.verify:
        if not args.out.exists():
            print(f"no snapshot at {args.out}")
            return 1
        snapshot = json.loads(args.out.read_text(encoding="utf-8"))
        print(f"verifying {args.out} ({len(snapshot.get('categories', []))} categories)")
        code = verify(snapshot)
        print("ok" if code == 0 else "problems found")
        return code

    if not args.wad.exists():
        print(f"Root.wad not found at {args.wad}; pass --wad")
        return 1

    snapshot = build_snapshot(args.wad, args.types)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(snapshot, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")

    print(f"wrote {args.out} ({len(snapshot['categories'])} categories)")
    for category in snapshot["categories"]:
        names = category["names"]
        print(f"  {category['key']:<20} {len(names)} locale(s): {names.get('en-US', '??')}")
    print()
    return verify(snapshot)


if __name__ == "__main__":
    sys.exit(main())
