"""Regenerate bartlebot/data/dialog_captions.json from the game's Root.wad.

Run this when a game patch changes the wording of a modal, or when a new dialog is added
to bartlebot.dialog_captions.KNOWN_KEYS. Everything else reads the checked-in snapshot,
so neither the app nor its tests need the game installed.

WHY EVERY LOCALE
    Wizard101 resolves lang keys to display text before it reaches memory, so a client
    running in French shows French caption text. Matching English would fail there --
    and fail by matching nothing, which a caller reads as "no dialog is up". So the
    snapshot carries all seven locales for every key, and matching tries them all.

WHY A SNAPSHOT IS SAFE
    Unlike the name tables, nothing here is index-based: a caption is looked up by its
    own key, so a stale snapshot cannot mis-identify a dialog. It can only fail to
    recognise one whose wording changed, and bartlebot.dialog_captions reports an
    unrecognised caption as None rather than guessing -- callers then fall back to their
    previous button-based behaviour.

    The one real risk is a *shortened* caption: if new wording is a substring of the old,
    the old fingerprint still matches. The --verify pass below re-reads the snapshot it
    just wrote and reports any key whose fingerprint matches more than one key's text.

USAGE
    uv run python tools/dump_dialog_captions.py
    uv run python tools/dump_dialog_captions.py --wad "D:/Games/Wizard101/Data/GameData/Root.wad"
    uv run python tools/dump_dialog_captions.py --verify      # no write; check the current file
"""

from __future__ import annotations

import argparse
import asyncio
import json
import sys
from collections import defaultdict
from datetime import date
from pathlib import Path

from wizwalker.file_readers.wad import Wad

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from bartlebot.dialog_captions import (  # noqa: E402
    CAPTIONS_PATH,
    KNOWN_KEYS,
    MIN_LITERAL_LEN,
    _fingerprint,
    normalize,
)

# Captions are printed in seven locales, including Greek, which a cp1252 console cannot
# encode. Without this the tool dies on its own progress output.
sys.stdout.reconfigure(encoding="utf-8", errors="replace")

DEFAULT_WAD = Path(r"C:\ProgramData\KingsIsle Entertainment\Wizard101\Data\GameData\Root.wad")

# The game ships these seven. A locale missing a key is normal -- later additions were
# not always translated -- and is simply absent from that key's entry.
LOCALES = ("de", "el", "en-US", "es", "fr", "it", "pl")

# Keys that are bare numbers are not unique across .lang files, so KNOWN_KEYS writes them
# as "<file stem>:<key>". Anything without a colon lives in GUI.lang.
DEFAULT_LANG_FILE = "GUI"


def split_key(known_key: str) -> tuple[str, str]:
    """Split a KNOWN_KEYS entry into (lang file stem, lang key)."""
    stem, _, key = known_key.rpartition(":")
    return (stem or DEFAULT_LANG_FILE), key


def parse_lang(raw: bytes) -> dict[str, str]:
    """Parse a .lang file into {key: display text}.

    UTF-16LE with CRLF endings, a one-line header, then fixed three-line records:

        key
        translator description, OFTEN BUT NOT ALWAYS BLANK
        display text

    The middle line is the trap. It reads as blank in most records, which makes the
    format look like `key / blank / value` -- and a parser that requires it blank
    silently drops every documented key instead of failing. That cost us GoToFriendFail,
    whose description was mistaken for its value, so the key looked unusable and was
    dropped from KNOWN_KEYS.

    Records are therefore sliced at a fixed stride rather than walked. Values never
    contain a literal newline: the game wraps with <br> and escaped \\n instead.
    """
    lines = raw.decode("utf-16-le", errors="replace").lstrip("\ufeff").split("\r\n")
    return {lines[i]: lines[i + 2] for i in range(1, len(lines) - 2, 3) if lines[i]}


async def build_snapshot(wad_path: Path) -> dict:
    wad = Wad(str(wad_path))
    available = set(await wad.names())

    # One read per (locale, lang file) rather than per key.
    wanted = {split_key(k)[0] for k in KNOWN_KEYS}
    tables: dict[tuple[str, str], dict[str, str]] = {}
    for locale in LOCALES:
        for stem in sorted(wanted):
            path = f"Locale/{locale}/{stem}.lang"
            if path not in available:
                continue
            tables[(locale, stem)] = parse_lang(await wad.get_file(path))

    captions: dict[str, dict[str, str]] = {}
    for known_key in KNOWN_KEYS:
        stem, key = split_key(known_key)
        by_locale = {locale: text for locale in LOCALES if (text := tables.get((locale, stem), {}).get(key))}
        if by_locale:
            captions[known_key] = by_locale
        else:
            print(f"  !! {known_key}: not found in any locale")

    return {
        "_comment": (
            "Generated by tools/dump_dialog_captions.py -- do not hand-edit. "
            "See bartlebot/dialog_captions.py for how these are matched."
        ),
        "generated": date.today().isoformat(),
        "source": str(wad_path),
        "captions": captions,
    }


def verify(snapshot: dict) -> int:
    """Report keys with no usable fingerprint, or fingerprints that collide. Returns exit code."""
    captions: dict[str, dict[str, str]] = snapshot.get("captions", {})
    problems = 0

    owners: dict[str, set[str]] = defaultdict(set)
    for key, by_locale in captions.items():
        for locale, text in by_locale.items():
            fingerprint = _fingerprint(text)
            if fingerprint is None:
                print(f"  !! {key} [{locale}]: no literal run of {MIN_LITERAL_LEN}+ chars -- {text[:70]!r}")
                problems += 1
                continue
            owners[fingerprint].add(key)

    for fingerprint, keys in owners.items():
        if len(keys) > 1:
            print(f"  !! fingerprint shared by {sorted(keys)}: {fingerprint[:70]!r}")
            problems += 1

    # A fingerprint that is a substring of another key's text matches both. Longest-first
    # ordering makes the specific one win, but it is still worth surfacing.
    for fingerprint, keys in owners.items():
        owner = next(iter(keys))
        for other_key, by_locale in captions.items():
            if other_key == owner:
                continue
            if any(fingerprint in normalize(text).replace("\x00", " ") for text in by_locale.values()):
                print(f"  ~  {owner}'s fingerprint also appears inside {other_key}")
                problems += 1

    missing = [key for key in KNOWN_KEYS if key not in captions]
    for key in missing:
        print(f"  !! {key}: absent from the snapshot")
        problems += 1

    return 1 if problems else 0


async def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--wad", type=Path, default=DEFAULT_WAD, help="path to Root.wad")
    ap.add_argument("--out", type=Path, default=CAPTIONS_PATH, help="where to write the snapshot")
    ap.add_argument("--verify", action="store_true", help="check the existing snapshot; do not write")
    args = ap.parse_args()

    if args.verify:
        if not args.out.exists():
            print(f"no snapshot at {args.out}")
            return 1
        snapshot = json.loads(args.out.read_text(encoding="utf-8"))
        print(f"verifying {args.out} ({len(snapshot.get('captions', {}))} keys)")
        code = verify(snapshot)
        print("ok" if code == 0 else "problems found")
        return code

    if not args.wad.exists():
        print(f"Root.wad not found at {args.wad}; pass --wad")
        return 1

    snapshot = await build_snapshot(args.wad)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(snapshot, indent=1, ensure_ascii=False), encoding="utf-8")

    print(f"wrote {args.out} ({len(snapshot['captions'])}/{len(KNOWN_KEYS)} keys)")
    for key, by_locale in snapshot["captions"].items():
        print(f"  {key:<42} {len(by_locale)} locale(s): {''.join(sorted(by_locale))[:40]}")
    print()
    return verify(snapshot)


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
