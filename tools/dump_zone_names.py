"""Regenerate bartlebot/game/data/zone_names.json from the game files.

Run this when a game patch adds a zone, or renames one in any locale. Everything else reads
the checked-in snapshot, so neither the app nor its tests need the game installed.

WHAT IT READS
    Every zone in Root.wad's zonemap.nav, then that zone's own wad: gamedata.bin's
    m_zoneDisplayName is a key like WizardZone_ColossusBlvd, and Locale/<loc>/WizardZone.lang
    holds the text for it in each of the seven locales.

    The snapshot keeps the two apart -- zone path -> key, key -> {locale: text} -- because
    side rooms share their street's key, so the texts would otherwise be stored hundreds of
    times over.

WHY EVERY LOCALE
    A zone-list object shows destinations in the client's own language, and memory holds the
    resolved text, so an English-only entry is not found on a French client. Same reasoning
    as world_names.json; see bartlebot/game/worlds.py.

USAGE
    uv run python tools/dump_zone_names.py              # about 30 seconds: it opens every zone wad
    uv run python tools/dump_zone_names.py --verify     # no write; check the current file
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import date
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))
sys.path.insert(0, str(REPO / "tools" / "zone_graph"))

import zonemap_nav  # noqa: E402
from wad_common import GAME_DATA, Deserializer, root_wad, text, zone_display_names  # noqa: E402
from zone_data import zone_record  # noqa: E402

from bartlebot.game import zone_nav  # noqa: E402
from bartlebot.game.worlds import LOCALES  # noqa: E402
from bartlebot.game.zone_names import ZONE_NAMES_PATH  # noqa: E402

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

_PREFIX = "WizardZone_"


def build_snapshot(game_data: Path) -> dict:
    root = root_wad(game_data)
    tables = {locale: zone_display_names(root, locale) for locale in LOCALES}
    deserialize = Deserializer()

    zones: dict[str, str] = {}
    for zone in zonemap_nav.load(game_data).names:
        try:
            key = text(zone_record(zone, deserialize, game_data)["m_zoneDisplayName"]).removeprefix(_PREFIX)
        except (FileNotFoundError, KeyError):
            continue  # no wad, or no gamedata.bin in it
        if key:
            zones[zone] = key

    names = {
        key: by_locale
        for key in sorted(set(zones.values()))
        if (by_locale := {locale: tables[locale][key] for locale in LOCALES if tables[locale].get(key)})
    }
    return {
        "_comment": "Generated by tools/dump_zone_names.py -- do not hand-edit. See bartlebot/game/zone_names.py.",
        "generated": date.today().isoformat(),
        "zones": dict(sorted(zones.items())),
        "names": names,
    }


def verify(snapshot: dict) -> int:
    """Report map zones the snapshot cannot name in English. Returns an exit code."""
    zones, names = snapshot.get("zones", {}), snapshot.get("names", {})
    problems = 0
    for world in zone_nav.load().worlds.values():
        for zone in world.zones:
            if "en-US" not in names.get(zones.get(zone, ""), {}) and not world.label(zone):
                print(f"  !! {zone}: no English name and no label in zone_nav.json")
                problems += 1
    return 1 if problems else 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--game-data", type=Path, default=GAME_DATA, help="the Wizard101 Data/GameData directory")
    ap.add_argument("--out", type=Path, default=ZONE_NAMES_PATH, help="where to write the snapshot")
    ap.add_argument("--verify", action="store_true", help="check the existing snapshot; do not write")
    args = ap.parse_args()

    if args.verify:
        snapshot = json.loads(args.out.read_text(encoding="utf-8"))
    else:
        snapshot = build_snapshot(args.game_data)
        args.out.write_text(json.dumps(snapshot, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"wrote {args.out}: {len(snapshot['zones'])} zones, {len(snapshot['names'])} names")
    code = verify(snapshot)
    print("ok" if code == 0 else "problems found")
    return code


if __name__ == "__main__":
    sys.exit(main())
