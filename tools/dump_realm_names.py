"""Regenerate bartlebot/data/realm_names.json from the game's Root.wad.

Run this when a game patch adds a realm, retires one, or renames one in any locale.
Everything else reads the checked-in snapshot, so neither the app nor its tests need
the game installed.

WHAT IT READS
    Locale/<loc>/RealmNames.lang, keyed by the realm's English name and valued with
    the localized text the realm list shows:

        Balestrom  -> Balestrom / Hagelkorn / ...
        Wraith     -> Wraith / Schrecker / ...

    The key is stable across locales and is what the Favorite Realm setting stores; the
    realm list in memory shows the *resolved* text, so a client in German lists
    "Hagelkorn", and the node has to match against every locale to find it. A key whose
    display text is blank in en-US (``Wu``, as of this writing) is a retired realm the
    list no longer offers, and is dropped.

    Locale/<loc>/GUI.lang's ``Yes`` and ``No`` keys, for the same reason: the Remember
    Realm option on the gameplay settings page shows its value as localized text, and
    reading it is the only way to know which way to toggle it.

WHY A SNAPSHOT IS SAFE
    Nothing here is index-based: a realm is looked up by its own key, so a stale
    snapshot cannot mis-name one. It can only fail to list a realm the game has just
    added, which the Favorite Realm picker then cannot offer.

USAGE
    uv run python tools/dump_realm_names.py
    uv run python tools/dump_realm_names.py --wad "D:/Games/Wizard101/Data/GameData/Root.wad"
    uv run python tools/dump_realm_names.py --verify      # no write; check the current file
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import date
from pathlib import Path

from katsuba.wad import Archive

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from bartlebot.realms import LOCALES, REALM_NAMES_PATH  # noqa: E402

# Realm names include Greek, which a cp1252 console cannot encode. Without this the
# tool dies on its own progress output.
sys.stdout.reconfigure(encoding="utf-8", errors="replace")

DEFAULT_WAD = Path(r"C:\ProgramData\KingsIsle Entertainment\Wizard101\Data\GameData\Root.wad")

REALM_LANG_FILE = "RealmNames"
GUI_LANG_FILE = "GUI"
YES_NO_KEYS = ("Yes", "No")


def parse_lang(raw: bytes) -> dict[str, str]:
    """Parse a .lang file into {key: display text}.

    UTF-16LE with CRLF endings, a one-line header, then fixed three-line records of
    key / translator description / display text. Slice at a fixed stride rather than
    walking -- the description is usually but not always blank. Same format and same
    trap as tools/dump_world_names.py.
    """
    lines = raw.decode("utf-16-le", errors="replace").lstrip("\ufeff").split("\r\n")
    return {lines[i]: lines[i + 2] for i in range(1, len(lines) - 2, 3) if lines[i]}


def _tables(archive: Archive, lang_file: str) -> dict[str, dict[str, str]]:
    tables: dict[str, dict[str, str]] = {}
    for locale in LOCALES:
        path = f"Locale/{locale}/{lang_file}.lang"
        try:
            raw = archive[path]
        except KeyError:
            print(f"  !! {path}: not in the archive")
            continue
        tables[locale] = parse_lang(raw)
    return tables


def _by_key(tables: dict[str, dict[str, str]], keys) -> dict[str, dict[str, str]]:
    return {
        key: by_locale
        for key in keys
        if (by_locale := {locale: text for locale in LOCALES if (text := tables.get(locale, {}).get(key))})
    }


def build_snapshot(wad_path: Path) -> dict:
    archive = Archive.mmap(str(wad_path))

    realm_tables = _tables(archive, REALM_LANG_FILE)
    # A realm the English table names but gives no text is retired: the list does not
    # offer it, so the picker must not either.
    english = realm_tables.get("en-US", {})
    keys = sorted(key for key, text in english.items() if text)
    realms = _by_key(realm_tables, keys)

    gui_tables = _tables(archive, GUI_LANG_FILE)
    yes_no = _by_key(gui_tables, YES_NO_KEYS)

    return {
        "_comment": (
            "Generated by tools/dump_realm_names.py -- do not hand-edit. "
            "See bartlebot/realms.py for how these are used."
        ),
        "generated": date.today().isoformat(),
        "source": str(wad_path),
        "realms": realms,
        "yes_no": yes_no,
    }


def verify(snapshot: dict) -> int:
    """Report what the snapshot cannot answer. Returns an exit code."""
    realms: dict[str, dict[str, str]] = snapshot.get("realms", {})
    yes_no: dict[str, dict[str, str]] = snapshot.get("yes_no", {})
    problems = 0

    if not realms:
        print("  !! no realms at all")
        problems += 1
    for key, by_locale in realms.items():
        if "en-US" not in by_locale:
            print(f"  !! {key}: no en-US name")
            problems += 1

    for key in YES_NO_KEYS:
        absent = [locale for locale in LOCALES if locale not in yes_no.get(key, {})]
        if absent:
            print(f"  !! {key}: untranslated in {', '.join(absent)}; Remember Realm cannot be read there")
            problems += 1

    # Two realms sharing a display text in some locale would make a match ambiguous.
    seen: dict[tuple[str, str], str] = {}
    for key, by_locale in realms.items():
        for locale, text in by_locale.items():
            other = seen.setdefault((locale, text.casefold()), key)
            if other != key:
                print(f"  !! {locale}: {text!r} names both {other} and {key}")
                problems += 1

    return 1 if problems else 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--wad", type=Path, default=DEFAULT_WAD, help="path to Root.wad")
    ap.add_argument("--out", type=Path, default=REALM_NAMES_PATH, help="where to write the snapshot")
    ap.add_argument("--verify", action="store_true", help="check the existing snapshot; do not write")
    args = ap.parse_args()

    if args.verify:
        if not args.out.exists():
            print(f"no snapshot at {args.out}")
            return 1
        snapshot = json.loads(args.out.read_text(encoding="utf-8"))
        print(f"verifying {args.out} ({len(snapshot.get('realms', {}))} realms)")
        code = verify(snapshot)
        print("ok" if code == 0 else "problems found")
        return code

    if not args.wad.exists():
        print(f"Root.wad not found at {args.wad}; pass --wad")
        return 1

    snapshot = build_snapshot(args.wad)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(snapshot, indent=1, ensure_ascii=False), encoding="utf-8")

    realms = snapshot["realms"]
    print(f"wrote {args.out} ({len(realms)} realms)")
    for key, by_locale in realms.items():
        print(f"  {key:<12} {len(by_locale)} locale(s)")
    print()
    return verify(snapshot)


if __name__ == "__main__":
    sys.exit(main())
