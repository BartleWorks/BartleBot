"""Zone display names in every locale, from the checked-in snapshot.

``bartlebot/game/data/zone_names.json`` is generated by ``tools/dump_zone_names.py``. It maps a
zone path to its display-name key and the key to its text per locale, since side rooms share
their street's key.

Two uses, and they want different things:

- **Matching what a client shows** -- a zone-list entry -- needs every locale, because memory
  holds the text in the client's language. ``display_names()`` returns all of them.
- **Showing a zone to the user** needs one readable name. ``label()`` prefers the label the
  navigation map gives a zone whose game name is ambiguous ("Zanadu Sewers" is "Zanadu" in
  game), then the English name, then the path's last segment.

Never key anything on the English text: key on the zone path.
"""

from __future__ import annotations

import json
import logging
import re
from functools import cache
from pathlib import Path

from bartlebot.game.worlds import LOCALES

logger = logging.getLogger(__name__)

ZONE_NAMES_PATH = Path(__file__).resolve().parent / "data" / "zone_names.json"


@cache
def _snapshot() -> tuple[dict[str, str], dict[str, dict[str, str]]]:
    try:
        raw = json.loads(ZONE_NAMES_PATH.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        logger.exception("Could not read zone names from %s", ZONE_NAMES_PATH)
        return {}, {}
    return raw.get("zones", {}), raw.get("names", {})


def display_names(zone: str) -> list[str]:
    """Every text the game might show for `zone`, deduped, en-US first; [] if unknown."""
    zones, names = _snapshot()
    by_locale = names.get(zones.get(zone, ""), {})
    return list(dict.fromkeys(by_locale[loc] for loc in ("en-US", *LOCALES) if loc in by_locale))


def label(zone: str) -> str:
    """One readable name for `zone`: the map's label, the English name, or the path's tail."""
    from bartlebot.game import zone_nav  # noqa: PLC0415  (zone_nav never imports this module)

    world = zone_nav.load().world_of(zone)
    if world is not None and (override := world.label(zone)):
        return override
    return next(iter(display_names(zone)), zone.rsplit("/", 1)[-1])


CHALLENGE_SUFFIXES: tuple[str, ...] = ("_Challenge", "_Hard", "_Adv", "Adv")
"""What the game appends to a dungeon zone's id for its Challenge Mode copy.

There is no one tag: Barkingham Palace uses ``_Challenge``, Aquila and most others ``_Hard``,
Karamelle and parts of Darkmoor ``_Adv`` (once with no underscore). The copy is a separate
zone, so a node standing in it reads a different zone_name() from the one a bot recorded.
"""


def challenge_variant_of(zone: str | None) -> str | None:
    """The ordinary zone `zone` is the Challenge Mode copy of, or None if it is not one.

    Decided by the snapshot, not by the suffix alone: the zone must end in one of
    CHALLENGE_SUFFIXES *and* the game must have a zone of the same id without it. A zone
    that merely ends in "Adv" has no such sibling and is left alone.
    """
    if not zone:
        return None
    zones, _ = _snapshot()
    for suffix in CHALLENGE_SUFFIXES:
        base = zone[: -len(suffix)]
        if zone.endswith(suffix) and base in zones:
            return base
    return None


TIERED_GAUNTLETS: tuple[str, ...] = (
    "Housing_AV_Gauntlet/AV_Gauntlet_{tier}/AV_Gauntlet_{tier}_",
    "Housing_Gauntlet/KH_Gauntlet{tier}/KH_Gauntlet{tier}_",
    "Housing_PA_Gauntlet/PA_Gauntlet_{tier}/PA_Gauntlet_{tier}_",
    "Housing_VA_Gauntlet/VA_Clock_Gauntlet_{tier}/VA_Level{tier}_",
    "Housing_GHGauntlet/GH_WinterbaneGauntlet{tier}/GH_WinterbaneGauntlet{tier}_",
    "Housing_Gauntlet_Theater/Gauntlet_{tier}/TheaterGauntlet_G{tier}_",
    "Housing_Gauntlet_Voyage/Gauntlet_{tier}/",
)
"""Gauntlets the game copies once per level band, as the prefix of each room's zone.

The game picks the band from the players' levels, and every band is a separate zone: the
same rooms, at the same coordinates, under a different number (``PA_Gauntlet_40`` is the
level 40 copy of ``PA_Gauntlet_01``). The room is whatever follows the prefix.

Declared one family at a time, never by a suffix rule: ``WC_Sunken_City_T1`` to ``_T3`` are
three rooms of one dungeon, and Treasure Tower's ``_L01`` to ``_L30`` are its floors. The
Halloween gauntlet's Easy, Medium and Hard are a choice, not a band, and are left out.
"""


def _tier_pattern(prefix: str) -> re.Pattern[str]:
    before, _, rest = prefix.partition("{tier}")
    later = r"(?P=tier)".join(re.escape(part) for part in rest.split("{tier}"))
    return re.compile(rf"{re.escape(before)}(?P<tier>\d+){later}(?P<room>.+)")


_TIER_PATTERNS = tuple(_tier_pattern(prefix) for prefix in TIERED_GAUNTLETS)


def tier_of(zone: str) -> tuple[int, str, int] | None:
    """(family, room, level band) for a room of a TIERED_GAUNTLETS family, or None."""
    for family, pattern in enumerate(_TIER_PATTERNS):
        if match := pattern.fullmatch(zone):
            return family, match["room"], int(match["tier"])
    return None


@cache
def _lowest_tiers() -> dict[tuple[int, str], str]:
    """Each tiered room's zone in its lowest band, from the snapshot."""
    zones, _ = _snapshot()
    lowest: dict[tuple[int, str], tuple[int, str]] = {}
    for zone in zones:
        if (tier := tier_of(zone)) is not None:
            family, room, band = tier
            if (family, room) not in lowest or band < lowest[family, room][0]:
                lowest[family, room] = (band, zone)
    return {key: zone for key, (_, zone) in lowest.items()}


def canonical_zone(zone: str) -> str:
    """The zone a bot stores for `zone`: the one every duplicate of it is compared as.

    A Challenge Mode copy's is the ordinary zone it copies (#143), and a tiered gauntlet
    room's is the same room in its lowest level band. Any other zone's is itself. A bot
    means a place, and which of its copies the players land in is the game's choice.
    """
    zone = challenge_variant_of(zone) or zone
    if (tier := tier_of(zone)) is not None:
        return _lowest_tiers().get(tier[:2], zone)
    return zone


@cache
def labels() -> frozenset[str]:
    """Every text ``label()`` gives some zone in the snapshot."""
    zones, _ = _snapshot()
    return frozenset(label(zone) for zone in zones)
